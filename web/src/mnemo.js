/* ---------------- Mnemo Hooks: the Czech mnemonic word cards of the Mnemo Korean decks ----------------
   Data: GG_MNEMO (mnemo_data.js, generated by tools/mnemo_build.py). This section is the one place where
   the game speaks Czech, because the hooks only work in Czech; there is no romanization here either.
   Spaced repetition per card and direction, saved in S.mh, so a transfer code carries it too:
   S.mh.c[key] = [due day, interval in days, ease ×100, reviews in a row, lapses]
   keys: "<card id>:r" recognition, ":p" production, ":l" listening, "R:<root id>" a hanja root. */
const MN = typeof GG_MNEMO !== "undefined" ? GG_MNEMO : { roots: {}, ch: {} };
const MN_ALL = Object.values(MN.ch).flat();
const MN_BY = Object.fromEntries(MN_ALL.map(k => [k.id, k]));
const MN_CHOF = Object.fromEntries(Object.entries(MN.ch).flatMap(([c, l]) => l.map(k => [k.id, c])));
const MN_ROOTW = {}; MN_ALL.forEach(k => (k.r || []).forEach(r => (MN_ROOTW[r] = MN_ROOTW[r] || []).push(k)));
const mnCards = ch => MN.ch[ch.id] || [];
const MN_POS = { n: "podstatné jméno", v: "sloveso", a: "přídavné jméno", f: "fráze", o: "ostatní" };
const MN_ORIG = { k: ["韓", "původní korejské"], s: ["漢", "sino-korejské"], e: ["EN", "výpůjčka"], m: ["韓+漢", "smíšené"] };
const MN_RATE = [["again", "Znovu", "nevěděl jsem"], ["hard", "Těžké", "s námahou"], ["good", "Dobré", "věděl jsem"], ["easy", "Snadné", "hned"]];
const MN_NEW = 10, MN_ROUND = 20;
const mnS = () => S.mh || (S.mh = { c: {} });
const mnSt = key => mnS().c[key];
const mnDue = key => { const e = mnSt(key); return e && dayGap(today(), e[0]) <= 0; };
const mnPlain = s => String(s || "").replace(/[{}]/g, "");
const mnGram = k => /^-|\/|…|\(/.test(k.w);                  // grammar patterns (-고 나서, 아무 …(이)나): recognition only

/* audio: Supertonic recordings at speed 0.85 (the game's own lines are 0.92). The speed is part of the voice
   id, so the key (and the clip) differs from the game's: words in F1, example sentences in M1. Without a
   recording: the phone's Korean voice, else the browser's. */
const MN_VW = "F1/0.85", MN_VX = "M1/0.85";
function mnAudio(add) {
  Object.entries(MN.ch).forEach(([c, l]) => l.forEach(k => {
    const b = "m" + c.slice(2);
    if (!mnGram(k)) { add(b, MN_VW, k.w, "mnemo", k.id); (k.alt || []).forEach(a => add(b, MN_VW, a, "mnemo", k.id)); }
    if (k.ex) add(b, MN_VX, mnPlain(k.ex), "mnemoex", k.id);
  }));
}
const mnRecV = t => hasRec(MN_VW, t) ? MN_VW : hasRec(MN_VX, t) ? MN_VX : null;
const mnDroid = () => { try { return !!(window.AndroidApp && AndroidApp.ttsKo && AndroidApp.ttsKo()); } catch (e) { return false; } };
const mnCanSay = t => !!mnRecV(t) || mnDroid() || !!koVoice;
function mnSay(t, btn) {
  const v = mnRecV(t);
  if (v || !mnDroid()) return say(t, v || MN_VW, btn);
  stopSay(); try { AndroidApp.say(sayText(t)); } catch (e) {}
}
const mnStop = () => { stopSay(); try { if (window.AndroidApp && AndroidApp.hush) AndroidApp.hush(); } catch (e) {} };
const mnTts = (t, cls) => mnCanSay(t) ? `<button class="tts rec mhs ${cls || ""}" type="button" data-mh-say="${esc(t)}" aria-label="Přehrát">${SPK}</button>` : "";
function mnWire(root) {
  $$("[data-mh-say]", root).forEach(b => b.onclick = e => { e.stopPropagation(); e.preventDefault(); mnSay(b.dataset.mhSay, b); });
  $$("[data-mh-go]", root).forEach(b => b.onclick = e => { e.preventDefault(); const k = MN_BY[b.dataset.mhGo]; if (k) mnPeek(k); });
}

