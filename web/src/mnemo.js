/* ---------------- spaced repetition ---------------- */
function mnRate(key, g) {                                    // g: 0 again, 1 hard, 2 good, 3 easy
  const t = today(), A = mnS().c; let [, ivl, ease, reps, lap] = A[key] || [t, 0, 250, 0, 0];
  if (g === 0) { ivl = 0; ease = Math.max(130, ease - 20); reps = 0; lap++; }
  else {
    if (reps === 0) ivl = g === 3 ? 4 : 1;
    else if (reps === 1) ivl = g === 1 ? 2 : g === 2 ? 3 : 6;
    else ivl = Math.max(ivl + 1, Math.round(ivl * (g === 1 ? 1.2 : g === 2 ? ease / 100 : ease / 100 * 1.3)));
    ivl = Math.min(ivl, 365);
    if (g === 1) ease = Math.max(130, ease - 15); if (g === 3) ease += 15; reps++;
  }
  A[key] = [dayAdd(t, ivl), ivl, ease, reps, lap];
  if (g > 0 && key.endsWith(":r")) {                         // once a word is recognised, it is also asked the other way, and by ear
    const id = key.slice(0, -2), k = MN_BY[id];
    if (k && !mnGram(k)) { if (!A[id + ":p"]) A[id + ":p"] = [dayAdd(t, 1), 0, 250, 0, 0]; if (!A[id + ":l"] && mnCanSay(k.w)) A[id + ":l"] = [dayAdd(t, 2), 0, 250, 0, 0]; }
    (k && k.r || []).forEach(r => { if (MN.roots[r] && !A["R:" + r]) A["R:" + r] = [dayAdd(t, 1), 0, 250, 0, 0]; });
  }
  stampDay(); save();
}
function mnStat(cards) {                                     // new / learning / known, by recognition
  const b = [0, 0, 0]; let due = 0;
  cards.forEach(k => { const e = mnSt(k.id + ":r"); b[!e ? 0 : e[1] >= 21 ? 2 : 1]++; ["r", "p", "l"].forEach(m => { if (mnDue(k.id + ":" + m)) due++; }); });
  const roots = [...new Set(cards.flatMap(k => k.r || []))].filter(r => MN.roots[r]);
  roots.forEach(r => { if (mnDue("R:" + r)) due++; });
  return { n: cards.length, b, due, fresh: b[0], roots };
}
function mnQueue(cards) {
  const due = [], A = mnS().c;
  cards.forEach(k => ["r", "p", "l"].forEach(m => { const key = k.id + ":" + m; if (A[key] && mnDue(key) && (m !== "l" || mnCanSay(k.w))) due.push({ m, k, key }); }));
  [...new Set(cards.flatMap(k => k.r || []))].filter(r => MN.roots[r] && mnDue("R:" + r)).slice(0, 5).forEach(r => due.push({ m: "k", r, key: "R:" + r }));   // roots: five a round at most
  const fresh = cards.map((k, i) => ({ k, i })).filter(x => !A[x.k.id + ":r"]).sort((a, b) => (a.k.f || 3) - (b.k.f || 3) || a.i - b.i)
    .slice(0, MN_NEW).map(x => ({ m: "r", k: x.k, key: x.k.id + ":r", fresh: true }));
  const q = shuffle(due).slice(0, Math.max(MN_ROUND - fresh.length, MN_ROUND - MN_NEW)).concat(fresh).slice(0, MN_ROUND);
  // the basic particle drill (을/를, 이/가 …) was taken out on 11. 11. 2026: too easy for this level (user)
  return q;
}

/* particles: the form follows the last syllable */
const MN_PT = [["을", "를"], ["이", "가"], ["은", "는"], ["과", "와"], ["으로", "로"]];
function mnParticle(w, pair) {
  const last = w.slice(-1), t = (last.charCodeAt(0) - 0xAC00) % 28;
  if (pair[0] === "으로") return t === 0 || t === 8 ? "로" : "으로";    // ㄹ takes 로 as well
  return t === 0 ? pair[1] : pair[0];
}

