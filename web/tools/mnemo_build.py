#!/usr/bin/env python3
"""Mnemo Hooks: balíčky z projektu Mnemo Korean -> web/src/mnemo_data.js

Použití:  python3 web/tools/mnemo_build.py [složka]   (výchozí: mnemo/ v kořeni balíčku, tam jsou balíčky z projektu)
Balíček ko-topik3-NNx.json patří ke kapitole NN. Vyřazené karty (vyrazeno: true) se vynechají,
romanizace se do hry nepřenáší (pravidlo hry). Id karet zůstávají, takže postup přežije opravy.
"""
import json, re, sys, glob, os

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "mnemo")
out = os.path.join(os.path.dirname(__file__), "..", "src", "mnemo_data.js")

POS = {"podstatne_jmeno": "n", "sloveso": "v", "pridavne_jmeno": "a", "fraze": "f", "ostatni": "o"}
TYP = {"puvodni": "k", "sino": "s", "vypujcka": "e", "smisene": "m"}

def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)

roots_doc = load(os.path.join(src, "ko-koreny.json"))
roots = {r["id"]: [r["hangul"], r["hanja"], r["cs"]] for r in roots_doc["koreny"]}

chapters, seen, warn = {}, {}, []
files = sorted(glob.glob(os.path.join(src, "ko-topik3-*.json")))
if not files:
    sys.exit("Ve složce %s nejsou žádné ko-topik3-*.json" % src)
for p in files:
    m = re.search(r"ko-topik3-(\d\d)[a-z]?\.json$", os.path.basename(p))
    if not m:
        warn.append("přeskočeno (neznámý název): " + p); continue
    ch = "ch%d" % int(m.group(1))
    deck = load(p)
    for c in deck["karty"]:
        if c.get("vyrazeno"):
            continue
        if c["id"] in seen:
            warn.append("duplicitní id %s (%s a %s)" % (c["id"], seen[c["id"]], os.path.basename(p))); continue
        seen[c["id"]] = os.path.basename(p)
        x = c.get("extra") or {}
        k = {"id": c["id"], "w": c["slovo"], "cs": c.get("cs", ""), "en": c.get("en", ""),
             "p": POS.get(c.get("slovni_druh"), "o"), "f": c.get("frekvence", 3), "t": c.get("tema", "")}
        def put(key, val):
            if val not in (None, "", [], {}, False):
                k[key] = val
        put("alt", c.get("alternativy"))
        put("vh", c.get("vyslov_hangul"))
        put("cu", c.get("cs_upresneni"))
        put("ex", c.get("priklad"))
        put("exc", c.get("priklad_cs"))
        put("m", c.get("mnemo"))
        put("r", c.get("koreny"))
        put("fam", c.get("rodina"))
        put("pl", c.get("plete_se_s"))
        vz = c.get("viz_tez")
        put("vz", [vz] if isinstance(vz, str) else vz)
        put("ov", bool(c.get("overit")))
        put("o", TYP.get(x.get("typ")))
        put("zen", x.get("z_anglictiny"))
        put("hada", bool(x.get("hada")))
        put("tv", x.get("tvary"))
        put("irr", x.get("nepravidelnost"))
        put("hon", x.get("honorifikum"))
        put("poc", x.get("pocitadlo"))
        put("rada", x.get("rada"))
        for r in c.get("koreny") or []:
            if r not in roots:
                warn.append("%s: kořen %s chybí v ko-koreny.json" % (c["id"], r))
        chapters.setdefault(ch, []).append(k)

# odkazy (viz_tez, plete_se_s) na karty, které ve hře nejsou, jen ohlásit
ids = set(seen)
for cards in chapters.values():
    for k in cards:
        for f in ("vz", "pl"):
            for t in k.get(f, []):
                if t not in ids:
                    warn.append("%s: %s odkazuje na %s, který v balíčcích není" % (k["id"], f, t))

used = {r for cards in chapters.values() for k in cards for r in k.get("r", [])}
data = {"roots": {r: v for r, v in roots.items() if r in used},
        "ch": {c: chapters[c] for c in sorted(chapters, key=lambda s: int(s[2:]))}}
js = "/* Mnemo Hooks: generated by web/tools/mnemo_build.py from the Mnemo Korean decks. Do not edit by hand. */\n" \
     "const GG_MNEMO = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
with open(out, "w", encoding="utf-8") as f:
    f.write(js)
n = sum(len(v) for v in chapters.values())
print("mnemo_data.js: %d karet, %d kořenů, kapitoly %s, %d kB" % (n, len(data["roots"]), ", ".join("%s=%d" % (c, len(v)) for c, v in data["ch"].items()), len(js.encode()) // 1024))
for w in warn:
    print("POZOR:", w)
